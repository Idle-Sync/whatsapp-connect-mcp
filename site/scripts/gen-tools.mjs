#!/usr/bin/env node
/**
 * Generate the tools reference from the running server, so the docs can never
 * drift from the release. Typing 28 tools by hand goes stale in two releases.
 *
 *   whatsapp-connect-mcp serve --http 127.0.0.1:2178
 *   npm run gen:tools
 *
 * Env:
 *   WCM_URL     default http://127.0.0.1:2178
 *   WCM_TOKEN   default: read from the config dir's .http-token
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir, platform } from 'node:os';
import { join } from 'node:path';

const URL_BASE = process.env.WCM_URL || 'http://127.0.0.1:2178';
const OUT = new URL('../content/docs/tools.md', import.meta.url);

function configDir() {
  if (process.env.WCM_CONFIG_DIR) return process.env.WCM_CONFIG_DIR;
  if (platform() === 'darwin')
    return join(homedir(), 'Library', 'Application Support', 'whatsapp-connect-mcp');
  if (platform() === 'win32')
    return join(process.env.APPDATA || homedir(), 'whatsapp-connect-mcp');
  return join(homedir(), '.config', 'whatsapp-connect-mcp');
}

function token() {
  if (process.env.WCM_TOKEN) return process.env.WCM_TOKEN.trim();
  try {
    return readFileSync(join(configDir(), '.http-token'), 'utf8').trim();
  } catch {
    return '';
  }
}

/** Streamable HTTP replies with either JSON or an SSE stream. Handle both. */
function parseBody(text) {
  const trimmed = text.trim();
  if (trimmed.startsWith('{')) return JSON.parse(trimmed);
  for (const line of trimmed.split('\n')) {
    if (line.startsWith('data:')) {
      const payload = line.slice(5).trim();
      if (payload && payload !== '[DONE]') return JSON.parse(payload);
    }
  }
  throw new Error(`could not parse response: ${trimmed.slice(0, 200)}`);
}

let sessionId = null;

async function rpc(method, params, isNotification = false) {
  const headers = {
    'content-type': 'application/json',
    accept: 'application/json, text/event-stream',
  };
  const tok = token();
  if (tok) headers.authorization = `Bearer ${tok}`;
  if (sessionId) headers['mcp-session-id'] = sessionId;

  const body = { jsonrpc: '2.0', method };
  if (params) body.params = params;
  if (!isNotification) body.id = Math.floor(Math.random() * 1e6);

  const res = await fetch(URL_BASE, { method: 'POST', headers, body: JSON.stringify(body) });
  const sid = res.headers.get('mcp-session-id');
  if (sid) sessionId = sid;

  if (!res.ok) throw new Error(`${method}: HTTP ${res.status} ${await res.text()}`);
  if (isNotification) return null;

  const out = parseBody(await res.text());
  if (out.error) throw new Error(`${method}: ${out.error.message}`);
  return out.result;
}

/** A gated tool is one the server holds for approval. */
const GATED = new Set([
  'send_message', 'send_media', 'send_voice_note', 'send_reaction',
  'edit_message', 'delete_message', 'mark_read', 'create_poll',
  'schedule_send', 'cancel_scheduled', 'block_contact', 'unblock_contact',
]);

function firstSentence(text) {
  const s = (text || '').replace(/\s+/g, ' ').trim();
  const stop = s.search(/\.\s|\.$/);
  return stop === -1 ? s : s.slice(0, stop + 1);
}

function argList(tool) {
  const props = tool.inputSchema?.properties || {};
  const required = new Set(tool.inputSchema?.required || []);
  const names = Object.keys(props);
  if (!names.length) return '—';
  return names
    .map((n) => (required.has(n) ? `\`${n}\`` : `\`${n}?\``))
    .join(', ');
}

function table(tools) {
  const rows = tools.map(
    (t) => `| \`${t.name}\` | ${firstSentence(t.description)} | ${argList(t)} |`
  );
  return ['| Tool | What it does | Arguments |', '|---|---|---|', ...rows].join('\n');
}

const result = await rpc('initialize', {
  protocolVersion: '2025-06-18',
  capabilities: {},
  clientInfo: { name: 'wcm-docs-generator', version: '1.0.0' },
});
await rpc('notifications/initialized', {}, true);

const { tools } = await rpc('tools/list', {});
const read = tools.filter((t) => !GATED.has(t.name));
const write = tools.filter((t) => GATED.has(t.name));
const version = result?.serverInfo?.version ? ` v${result.serverInfo.version}` : '';

const md = `---
title: Tools
description: Every tool the server exposes, which ones are gated, and what each one takes.
---

<!-- GENERATED by scripts/gen-tools.mjs from the running server. Do not edit by hand. -->

${tools.length} tools${version}. ${read.length} read freely. **${write.length} stop at
[the gate](/docs/send-gate)** — every single time, whatever the model decides it wants.

An argument written \`like?\` is optional.

## Read and search

No gate. These never touch anyone else's phone.

${table(read)}

:::caution[How far back these reach is your phone's decision]
Not this server's. See [Limitations](/docs/limitations).
:::

## Send and act

Every one of these is held until you approve it. See
[the send gate](/docs/send-gate) for why that cannot be talked around.

${table(write)}
`;

writeFileSync(OUT, md);
console.log(`wrote ${tools.length} tools (${read.length} read, ${write.length} gated) → ${OUT.pathname}`);
